import torch
import torch.nn as nn


class EvidenceAwareGraphLayer(nn.Module):
    """
    Evidence-aware directed graph message-passing layer.

    Node input:
        [N, node_dim]

    Edge index:
        [2, E]
        edge_index[0] = source
        edge_index[1] = target

    Edge attributes:
        [E, 4]

        0: spatial distance
        1: token cosine similarity
        2: source provenance evidence
        3: target provenance evidence

    Message:
        m_ij = MLP(
            [h_i, h_j, edge_attr_ij]
        )

    Aggregation:
        mean of incoming messages

    Update:
        residual node update
    """

    def __init__(
        self,
        node_dim=771,
        hidden_dim=256,
        edge_dim=4,
    ):
        super().__init__()

        self.node_dim = node_dim
        self.hidden_dim = hidden_dim
        self.edge_dim = edge_dim

        self.node_in = nn.Sequential(
            nn.LayerNorm(node_dim),

            nn.Linear(
                node_dim,
                hidden_dim,
            ),

            nn.GELU(),
        )

        self.message_mlp = nn.Sequential(
            nn.Linear(
                hidden_dim * 2 + edge_dim,
                hidden_dim,
            ),

            nn.GELU(),

            nn.Linear(
                hidden_dim,
                hidden_dim,
            ),
        )

        self.update_mlp = nn.Sequential(
            nn.LayerNorm(
                hidden_dim * 2
            ),

            nn.Linear(
                hidden_dim * 2,
                hidden_dim,
            ),

            nn.GELU(),

            nn.Linear(
                hidden_dim,
                hidden_dim,
            ),
        )

        self.output_norm = nn.LayerNorm(
            hidden_dim
        )

    def forward(
        self,
        node_features,
        edge_index,
        edge_attr,
    ):
        """
        node_features:
            [N,771]

        returns:
            [N,256]
        """

        if node_features.ndim != 2:
            raise RuntimeError(
                "node_features must be [N,C]"
            )

        if edge_index.ndim != 2:
            raise RuntimeError(
                "edge_index must be [2,E]"
            )

        if edge_index.shape[0] != 2:
            raise RuntimeError(
                "edge_index first dimension "
                "must equal 2"
            )

        if edge_attr.ndim != 2:
            raise RuntimeError(
                "edge_attr must be [E,D]"
            )

        if edge_attr.shape[0] != edge_index.shape[1]:
            raise RuntimeError(
                "edge count mismatch"
            )

        if edge_attr.shape[1] != self.edge_dim:
            raise RuntimeError(
                "edge attribute dimension mismatch"
            )

        h = self.node_in(
            node_features
        )

        src = edge_index[0]
        dst = edge_index[1]

        source_h = h[src]
        target_h = h[dst]

        message_input = torch.cat(
            [
                source_h,
                target_h,
                edge_attr,
            ],
            dim=-1,
        )

        messages = self.message_mlp(
            message_input
        )

        # --------------------------------------------
        # Mean aggregation of incoming messages.
        # No torch_geometric dependency required.
        # --------------------------------------------

        aggregated = torch.zeros_like(
            h
        )

        aggregated.index_add_(
            0,
            dst,
            messages,
        )

        degree = torch.zeros(
            h.shape[0],
            1,
            device=h.device,
            dtype=h.dtype,
        )

        ones = torch.ones(
            dst.shape[0],
            1,
            device=h.device,
            dtype=h.dtype,
        )

        degree.index_add_(
            0,
            dst,
            ones,
        )

        aggregated = (
            aggregated
            / degree.clamp_min(1.0)
        )

        update_input = torch.cat(
            [
                h,
                aggregated,
            ],
            dim=-1,
        )

        delta = self.update_mlp(
            update_input
        )

        output = self.output_norm(
            h + delta
        )

        return output


class ProvenanceGNNV2(nn.Module):
    """
    Two-layer provenance GNN.

    Input:
        list/batch of graphs generated by
        ProvenanceGraphBuilder.

    Output:
        [B,196,256]
    """

    def __init__(
        self,
        node_dim=771,
        hidden_dim=256,
        edge_dim=4,
        depth=2,
    ):
        super().__init__()

        if depth < 1:
            raise ValueError(
                "depth must be >= 1"
            )

        layers = []

        layers.append(
            EvidenceAwareGraphLayer(
                node_dim=node_dim,
                hidden_dim=hidden_dim,
                edge_dim=edge_dim,
            )
        )

        for _ in range(
            depth - 1
        ):
            layers.append(
                EvidenceAwareGraphLayer(
                    node_dim=hidden_dim,
                    hidden_dim=hidden_dim,
                    edge_dim=edge_dim,
                )
            )

        self.layers = nn.ModuleList(
            layers
        )

        self.hidden_dim = hidden_dim

    def forward(
        self,
        node_features,
        edge_indices,
        edge_attributes,
    ):
        """
        node_features:
            [B,N,C]

        edge_indices:
            list length B

        edge_attributes:
            list length B
        """

        B = node_features.shape[0]

        if len(edge_indices) != B:
            raise RuntimeError(
                "edge_indices batch mismatch"
            )

        if len(edge_attributes) != B:
            raise RuntimeError(
                "edge_attributes batch mismatch"
            )

        outputs = []

        for b in range(B):

            h = node_features[b]

            for layer in self.layers:

                h = layer(
                    h,
                    edge_indices[b],
                    edge_attributes[b],
                )

            outputs.append(h)

        return torch.stack(
            outputs,
            dim=0,
        )